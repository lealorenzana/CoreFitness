import type { TrainingFocus } from './trainingFocus';

/**
 * The training plan generator.
 *
 * ## It is rules, and it is named as rules
 *
 * This is a deterministic function: the same answers produce the same plan,
 * every time, with no model and no network. That is a deliberate choice, not a
 * limitation to apologise for — this project has already shipped a chatbot that
 * invented gyms, coaches and prices that do not exist, and a plan that quietly
 * makes things up in front of a member is worse than one that is predictable.
 *
 * The vocabulary stays honest to match. Nothing in the interface calls this AI.
 *
 * ## Built so a model can be added later without touching this file
 *
 * `buildPlan` returns a **PlanSpec** — structured data, no prose. Turning that
 * into words happens in `planRender.ts`. That seam is the whole point: a hybrid
 * that wants a model to reword the plan conversationally replaces the renderer
 * and leaves the programming logic alone, so the facts stay generated by rules
 * that can be audited and the model only ever changes the phrasing. The stored
 * row keeps the spec, not the prose, so an old plan can be re-rendered by
 * whatever the app uses at the time.
 *
 * ## What it will not do
 *
 * No calorie targets, no macro splits, no weight goals. `trainingFocus.ts`
 * already sets the rule this follows:
 *
 *     These sentences describe the direction of a tape measurement against a
 *     stated intention. They do not say a member is healthy, unhealthy, on
 *     track, or failing, and they never suggest what anyone should eat or weigh.
 *
 * Individual dietary prescription from a lookup table is not something this can
 * do responsibly — it has no idea who is pregnant, diabetic, recovering from an
 * eating disorder, or sixteen. So nutrition here is general practice, the same
 * things a coach would say out loud on the gym floor, and anything individual
 * routes to a human. Nor does it program around injuries: a stated limitation
 * produces a referral to a trainer, never a modified exercise.
 */

export type Experience = 'beginner' | 'intermediate' | 'advanced';
export type Preference = 'gym' | 'classes' | 'both';

export interface PlanInputs {
  experience: Experience;
  focus: TrainingFocus;
  /** Realistic sessions per week. Clamped to 2-6; below 2 is not a programme. */
  daysPerWeek: number;
  /** Minutes per session, as the member actually has, not as they wish. */
  sessionMinutes: 30 | 45 | 60 | 90;
  preference: Preference;
  /** Free text. Its presence changes the plan's advice, never its exercises. */
  limitations: string;
}

export interface PlanExercise {
  name: string;
  sets: number;
  reps: string;
  /** Shown under the exercise. Technique cue or a substitution, never a claim. */
  note?: string;
}

export interface PlanDay {
  label: string;
  focus: string;
  exercises: PlanExercise[];
}

export interface PlanSpec {
  /** Schema version, so a stored plan can be re-rendered years later. */
  version: 1;
  builtAt: string;
  inputs: PlanInputs;
  splitName: string;
  /** Why this split, in the member's terms. */
  rationale: string;
  days: PlanDay[];
  conditioning: string[];
  progression: string[];
  nutrition: string[];
  /** Reasons to talk to an actual coach. Never empty. */
  seeACoach: string[];
}

