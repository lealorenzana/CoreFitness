-- 0282 — the assistants look things up and say where (RAG; plan docs/superpowers/plans/2026-11-27-rag.md).
--
-- One search, two rankings merged (hybrid): keyword (Postgres full text search) and meaning (pgvector,
-- with Supabase's built-in gte-small model, 384 numbers per text). Members say "stop my membership";
-- the Terms say "freeze": the meaning ranking finds it, the keyword ranking still catches exact words
-- ("PAR-Q", "BIR 2303"), and with no question embedding the keyword ranking answers alone.
--
--   * knowledge_chunks: the shared texts, one row per Terms or Privacy section and per guide step,
--     filled by supabase/knowledge/texts.sql (generated by scripts/knowledge-seed.mts, never typed).
--   * The gym's own texts are searched where they live: its current waiver and house rules, by paragraph.
--     Core Fitness's contact and the plans for gyms come from the platform's own settings, live.
--   * Embeddings are made only inside Edge Functions (knowledge-embed), with one model; a row whose text
--     changed is stale until it is embedded again (body_hash vs embedded_hash).
--   * Who reads what: a member or coach reads member texts; the desk adds staff texts; the owner adds
--     owner texts (Core Fitness's plans and prices). Only their own gym's waiver and house rules.
--   * RLS on and no policy on both tables: read only through search_knowledge(), written only by the
--     service role.
-- Safe to paste again.

create extension if not exists vector with schema extensions;

create table if not exists knowledge_chunks (
  id            text primary key,                         -- 'terms:freezing', 'guide:online-pay:3'
  source        text not null check (source in ('terms', 'privacy', 'guide', 'core_fitness')),
  audience      text not null check (audience in ('member', 'staff', 'owner')),
  title         text not null,
  body          text not null,                            -- what is shown and quoted
  extra         text,                                     -- searched, not shown (a guide's Filipino)
  link          text,                                     -- where the source opens, for the citation
  tsv           tsvector generated always as
                  (to_tsvector('english', title || ' ' || body || ' ' || coalesce(extra, ''))) stored,
  body_hash     text generated always as (md5(title || body || coalesce(extra, ''))) stored,
  embedding     extensions.vector(384),
  embedded_hash text
);
create index if not exists idx_knowledge_tsv on knowledge_chunks using gin (tsv);
alter table knowledge_chunks enable row level security;
revoke all on knowledge_chunks from public, anon, authenticated;

-- Embeddings of the texts that live elsewhere: a gym's waiver and house rules (by paragraph), and the
-- platform's own facts. `ref` names the paragraph, e.g. 'waiver:<id>:2'.
create table if not exists knowledge_vectors (
  ref        text primary key,
  gym_id     uuid,
  body_hash  text not null,
  embedding  extensions.vector(384) not null
);
alter table knowledge_vectors enable row level security;
revoke all on knowledge_vectors from public, anon, authenticated;

/** Every text the search can return, with its audience and the gym it belongs to (null: shared). */
create or replace function knowledge_corpus()
returns table (ref text, gym_id uuid, source text, audience text, title text, body text, link text, body_hash text)
language sql stable security definer set search_path = public, extensions as $$
  select c.id, null::uuid, c.source, c.audience, c.title, c.body || coalesce(E'\n' || c.extra, ''), c.link, c.body_hash
    from knowledge_chunks c
  union all
  -- The current waiver of each gym, paragraph by paragraph.
  select 'waiver:' || w.id || ':' || p.n, w.gym_id, 'waiver', 'member', w.title, p.txt, '/member/waiver', md5(p.txt)
    from (select distinct on (gym_id) * from gym_waivers where published_at is not null
           order by gym_id, version desc) w,
         lateral (select t.txt, t.n from regexp_split_to_table(w.body, E'\\n\\s*\\n') with ordinality t(txt, n)
                   where length(btrim(t.txt)) > 20) p
  union all
  -- The current house rules of each gym, paragraph by paragraph.
  select 'rules:' || r.id || ':' || p.n, r.gym_id, 'house_rules', 'member', 'House rules (version ' || r.version || ')',
         p.txt, '/terms#using', md5(p.txt)
    from (select distinct on (gym_id) * from gym_house_rules where published_at is not null
           order by gym_id, version desc) r,
         lateral (select t.txt, t.n from regexp_split_to_table(r.body, E'\\n\\s*\\n') with ordinality t(txt, n)
                   where length(btrim(t.txt)) > 10) p
  union all
  -- Who runs the app and how to reach them, from the platform's own settings (never typed in).
  select 'platform:contact', null, 'core_fitness', 'member', 'About ' || b.business_name,
         b.business_name || ' makes and runs this app for gyms. It keeps each gym''s records apart, and it is '
         || 'your gym, not ' || b.business_name || ', that sets prices, rules and refunds. To reach '
         || b.business_name || ': ' || concat_ws(', ', b.business_email, b.business_phone, b.business_address) || '.',
         null, md5(concat_ws('|', b.business_name, b.business_email, b.business_phone, b.business_address))
    from platform_billing b where b.id
  union all
  -- The plans Core Fitness sells to gyms: the owner's question, from the price list.
  select 'platform:plans', null, 'core_fitness', 'owner', 'Core Fitness plans for gyms', t.txt, '/subscription', md5(t.txt)
    from (select string_agg(p.name || ': ' || coalesce('PHP ' || p.price_monthly::text || ' a month', 'talk to us')
                   || coalesce(', PHP ' || p.price_yearly::text || ' a year', '')
                   || coalesce(', up to ' || p.max_members || ' members', '')
                   || coalesce(', up to ' || p.max_staff || ' staff', '')
                   || coalesce(', ' || p.ai_monthly_cap || ' assistant messages a month', '')
                   || coalesce('. ' || p.blurb, ''), E'\n' order by p.sort_order) as txt
            from platform_price_list() p) t
   where t.txt is not null;
$$;
revoke all on function knowledge_corpus() from public, anon, authenticated;

/** For knowledge-embed (service role): texts whose embedding is missing or older than their words. */
create or replace function knowledge_stale(p_limit int default 25)
returns table (ref text, gym_id uuid, body text, body_hash text)
language sql stable security definer set search_path = public, extensions as $$
  select k.ref, k.gym_id, k.title || E'\n' || k.body, k.body_hash
    from knowledge_corpus() k
    left join knowledge_chunks c on c.id = k.ref
    left join knowledge_vectors v on v.ref = k.ref
   where (c.id is not null and c.embedded_hash is distinct from c.body_hash)
      or (c.id is null and (v.ref is null or v.body_hash <> k.body_hash))
   limit greatest(1, least(p_limit, 100));
$$;
revoke all on function knowledge_stale(int) from public, anon, authenticated;
grant execute on function knowledge_stale(int) to service_role;

create or replace function knowledge_save_embedding(p_ref text, p_gym uuid, p_hash text, p_embedding extensions.vector(384))
returns boolean
language plpgsql security definer set search_path = public, extensions as $$
begin
  update knowledge_chunks set embedding = p_embedding, embedded_hash = p_hash where id = p_ref and body_hash = p_hash;
  if found then return true; end if;
  if exists (select 1 from knowledge_chunks where id = p_ref) then return false; end if;  -- changed meanwhile
  insert into knowledge_vectors (ref, gym_id, body_hash, embedding) values (p_ref, p_gym, p_hash, p_embedding)
  on conflict (ref) do update set gym_id = excluded.gym_id, body_hash = excluded.body_hash, embedding = excluded.embedding;
  return true;
end;
$$;
revoke all on function knowledge_save_embedding(text, uuid, text, extensions.vector) from public, anon, authenticated;
grant execute on function knowledge_save_embedding(text, uuid, text, extensions.vector) to service_role;

-- Vectors of paragraphs that no longer exist (a new waiver version) are swept here, never read: the
-- search joins the corpus, so a stale vector cannot surface old words.
create or replace function knowledge_sweep() returns int
language sql security definer set search_path = public, extensions as $$
  with gone as (delete from knowledge_vectors v where not exists (select 1 from knowledge_corpus() k where k.ref = v.ref) returning 1)
  select count(*)::int from gone;
$$;
revoke all on function knowledge_sweep() from public, anon, authenticated;
grant execute on function knowledge_sweep() to service_role;

/** The caller's reading level in their current gym: member (members, coaches), staff (desk), owner. Null: none. */
create or replace function knowledge_audience() returns text
language sql stable security definer set search_path = public as $$
  select case max(case r.role when 'admin' then 3 when 'staff' then 2 else 1 end)
           when 3 then 'owner' when 2 then 'staff' when 1 then 'member' end
    from gym_roles r
   where r.user_id = auth.uid() and r.gym_id = current_gym_id() and r.status = 'active';
$$;
revoke all on function knowledge_audience() from public, anon, authenticated;

/**
 * The search. Keyword rank and meaning rank over what the caller may read, merged by reciprocal rank
 * fusion (each list's rank r adds 1 / (50 + r)). p_embedding is the question's gte-small embedding, made
 * by the caller's Edge Function; null means keyword only.
 */
create or replace function search_knowledge(p_query text, p_embedding extensions.vector(384) default null, p_limit int default 6)
returns table (ref text, source text, title text, body text, link text, score float8)
language plpgsql stable security definer set search_path = public, extensions as $$
#variable_conflict use_column
declare
  v_aud text := knowledge_audience();
  v_gym uuid := current_gym_id();
  v_q tsquery;
begin
  if v_aud is null then
    raise exception 'Sign in to a gym first.' using errcode = '42501';
  end if;
  if coalesce(length(btrim(p_query)), 0) = 0 or length(p_query) > 500 then
    raise exception 'Ask a question of up to 500 characters.';
  end if;
  -- Any word may match (a whole question rarely sits in one clause); the rank rewards clauses matching more.
  v_q := nullif(replace(websearch_to_tsquery('english', p_query)::text, ' & ', ' | '), '')::tsquery;
  return query
  with mine as (
    select k.* from knowledge_corpus() k
     where (k.gym_id is null or k.gym_id = v_gym)
       and case k.audience when 'member' then true
                           when 'staff' then v_aud in ('staff', 'owner')
                           else v_aud = 'owner' end
  ),
  by_words as (
    select m.ref, row_number() over (order by ts_rank_cd(to_tsvector('english', m.title || ' ' || m.body), v_q) desc) rn
      from mine m
     where to_tsvector('english', m.title || ' ' || m.body) @@ v_q
     limit 20
  ),
  by_meaning as (
    select m.ref, row_number() over (order by coalesce(c.embedding, v.embedding) <=> p_embedding) rn
      from mine m
      left join knowledge_chunks c on c.id = m.ref and c.embedded_hash = c.body_hash
      left join knowledge_vectors v on v.ref = m.ref and v.body_hash = m.body_hash
     where p_embedding is not null and coalesce(c.embedding, v.embedding) is not null
       and (coalesce(c.embedding, v.embedding) <=> p_embedding) < 0.5     -- cosine similarity above 0.5
     order by coalesce(c.embedding, v.embedding) <=> p_embedding
     limit 20
  ),
  fused as (
    select f.ref, sum(1.0 / (50 + f.rn))::float8 score
      from (select * from by_words union all select * from by_meaning) f
     group by f.ref
  )
  select m.ref, m.source, m.title, m.body, m.link, f.score
    from fused f join mine m on m.ref = f.ref
   order by f.score desc, m.ref
   limit greatest(1, least(p_limit, 10));
end;
$$;
revoke all on function search_knowledge(text, extensions.vector, int) from public, anon;
grant execute on function search_knowledge(text, extensions.vector, int) to authenticated;

